const glyphOf = (ch: string) => HANGUL[ch] ?? GLYPHS[ch];

/** Hauteur d'un texte, en pixels (10 s'il contient du hangeul, sinon 5). */
export function textHeight(text: string) {
  for (const ch of text) if (HANGUL[ch]) return 10;
  return 5;
}

/** Largeur d'un texte, en pixels. */
export function textWidth(text: string) {
  let w = 0;
  for (const ch of text.toUpperCase()) w += (glyphOf(ch)?.[0].length ?? 3) + 1;
  return Math.max(0, w - 1);
}

/** Écrit un texte en pixels ; renvoie sa largeur. */
export function pixelText(g: G, text: string, x: number, y: number, color: string) {
  g.fillStyle = color;
  let cx = Math.round(x);
  const h = textHeight(text);
  for (const ch of text.toUpperCase()) {
    const glyph = glyphOf(ch) ?? GLYPHS[' '];
    // les petits caractères (chiffres…) se centrent à côté du hangeul
    const dy = Math.round(y) + Math.floor((h - glyph.length) / 2);
    for (let r = 0; r < glyph.length; r++) {
      const row = glyph[r];
      for (let c = 0; c < row.length; c++) if (row[c] === '#') g.fillRect(cx + c, dy + r, 1, 1);
    }
    cx += glyph[0].length + 1;
  }
  return cx - Math.round(x) - 1;
}
